static void print_digest(const char *label, const uint8_t digest[32])
{
    size_t i;
    (void)printf("%s=0x", label);
    for (i = 0U; i < 32U; ++i) (void)printf("%02x", digest[i]);
    (void)printf("\n");
}

static int emit_case(const char *prefix, size_t count, size_t leaf_index,
                     const uint8_t (*leaf_hashes)[32], lxp_arena *arena,
                     const uint8_t expected_root[32],
                     const uint8_t (*expected_siblings)[32],
                     size_t expected_depth)
{
    lxp_merkle_proof proof;
    uint8_t root[32];
    uint8_t built[32];
    char label[64];
    size_t i;
    if (lxp_merkle_build(leaf_hashes, count, arena, built) != LXP_OK) return 1;
    if (lxp_merkle_proof_generate(leaf_hashes, count, leaf_index, arena,
                                  &proof, root) != LXP_OK) return 1;
    if (memcmp(built, root, 32U) != 0) return 1;
    if (memcmp(root, expected_root, 32U) != 0) return 1;
    if ((size_t)proof.depth != expected_depth) return 1;
    for (i = 0U; i < expected_depth; ++i)
        if (memcmp(proof.siblings[i], expected_siblings[i], 32U) != 0) return 1;
    if (lxp_merkle_proof_verify(leaf_hashes[leaf_index], &proof, root) != LXP_OK)
        return 1;
    (void)snprintf(label, sizeof(label), "%s.root", prefix);
    print_digest(label, root);
    for (i = 0U; i < expected_depth; ++i) {
        (void)snprintf(label, sizeof(label), "%s.sibling[%u]", prefix,
                       (unsigned)i);
        print_digest(label, proof.siblings[i]);
    }
    return 0;
}

int main(void)
{
    uint8_t memory[8192];
    lxp_arena arena;
    uint8_t leaf_hashes[VECTOR_LEAF_COUNT][32];
    char label[64];
    size_t i;
    if (lxp_arena_init(&arena, memory, sizeof(memory)) != LXP_OK) return 1;
    for (i = 0U; i < (size_t)VECTOR_LEAF_COUNT; ++i) {
        if (lxp_merkle_leaf_hash(vector_values[i], strlen(vector_values[i]),
                                 leaf_hashes[i]) != LXP_OK) return 1;
        if (memcmp(leaf_hashes[i], expected_leaf_hashes[i], 32U) != 0) return 1;
        (void)snprintf(label, sizeof(label), "leaf[%u]", (unsigned)i);
        print_digest(label, leaf_hashes[i]);
    }
    if (emit_case("four", 4U, (size_t)VECTOR_LEAF_INDEX,
                  (const uint8_t (*)[32])leaf_hashes, &arena,
                  expected_four_leaf_root,
                  expected_four_leaf_siblings, 2U) != 0) return 1;
    if (emit_case("three", 3U, (size_t)VECTOR_LEAF_INDEX,
                  (const uint8_t (*)[32])leaf_hashes, &arena,
                  expected_three_leaf_root,
                  expected_three_leaf_siblings, 2U) != 0) return 1;
    return 0;
}
